INSTITUTE_BY_SHORT = {item.short_name: item for item in INSTITUTES}


def get_catalog_payload() -> list[dict]:
    return [
        {
            "full_name": item.full_name,
            "short_name": item.short_name,
            "departments": item.departments,
            "programs": item.programs,
        }
        for item in INSTITUTES
    ]


def validate_teacher_profile(
    institute_short_name: str | None, department_code: str | None
):
    if not department_code:
        raise ValueError("Для преподавателя необходимо выбрать кафедру")

    actual_institute = find_institute_by_department(department_code)
    if not actual_institute:
        raise ValueError(f"Кафедра с кодом {department_code} не найдена в каталоге")

    if institute_short_name and institute_short_name != actual_institute:
        raise ValueError(
            f"Кафедра {department_code} относится к {actual_institute}, а не к {institute_short_name}"
        )

    return actual_institute


def validate_student_profile(
    institute_short_name: str | None, program_code: str | None
):
    if not program_code:
        raise ValueError("Для студента необходимо выбрать направление подготовки")

    actual_institute = find_institute_by_program(program_code)
    if not actual_institute:
        raise ValueError(f"Направление с кодом {program_code} не найдено в каталоге")

    if institute_short_name and institute_short_name != actual_institute:
        raise ValueError(
            f"Направление {program_code} относится к {actual_institute}, а не к {institute_short_name}"
        )

    return actual_institute


def find_institute_by_department(department_code: str) -> str | None:
    for inst in INSTITUTES:
        for dept in inst.departments:
            if dept["code"] == department_code:
                return inst.short_name
    return None


def find_institute_by_program(program_code: str) -> str | None:
    for inst in INSTITUTES:
        for prog in inst.programs:
            if prog["code"] == program_code:
                return inst.short_name
    return None
